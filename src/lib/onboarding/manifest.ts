export const ONBOARDING_STEPS: readonly TourStep[] = RAW_STEPS.map((seed, index) => {
  const copy = ONBOARDING_STEP_COPY_PT_BR[seed.id];
  if (!copy) {
    throw new Error(`[Onboarding Manifest] Copy ausente para stepId "${seed.id}"`);
  }
  const normalizedTargetSelector = seed.selector.startsWith("[data-tour=")
    ? seed.selector
    : `[data-tour="${seed.selector}"]`;
  const normalizedCommand: TourCommand | undefined = seed.prepareCommand
    ? {
        ...seed.prepareCommand,
        command: seed.prepareCommand.command ?? seed.prepareCommand.name,
        type: seed.prepareCommand.type ?? seed.prepareCommand.name,
        surface: seed.prepareCommand.surface ?? seed.surface,
        payload: seed.prepareCommand.payload ?? seed.prepareCommand.params,
      }
    : undefined;

  return {
    id: seed.id,
    chapterId: seed.chapterId,
    orderIndex: index,
    order: index + 1,
    featureIds: seed.featureIds,
    functionalIds: seed.featureIds,
    view: seed.view,
    routePath: seed.routePath,
    surface: seed.surface,
    target: {
      scope: seed.surface,
      selector: seed.selector,
      demoItemId: seed.demoItemId,
    },
    targetSelector: normalizedTargetSelector,
    fallbackSelectors: [normalizedTargetSelector],
    title: copy.title,
    body: copy.body,
    ctaLabel:
      seed.id === "finish.complete"
        ? "Concluir treinamento"
        : seed.mode === "I"
          ? "Simular e avançar"
          : "Próximo passo",
    mode: seed.mode,
    requiredCapabilities: seed.requiredCapabilities ?? [],
    scenarioId: seed.scenarioId,
    prepareCommand: normalizedCommand,
    demoCommand: normalizedCommand,
    enterCommands: normalizedCommand ? [normalizedCommand] : undefined,
    completionRule: {
      type:
        seed.id === "finish.complete"
          ? "final_confirm"
          : seed.mode === "I"
            ? "demo_interaction_or_next"
            : "next_click",
      interactionEvent: seed.mode === "I" ? `demo:${seed.id}` : undefined,
    },
    completion: {
      type:
        seed.id === "finish.complete"
          ? "final_confirm"
          : seed.mode === "I"
            ? "demo_interaction"
            : "manual",
      demoAction: normalizedCommand?.name || "interact",
      demoPayload: normalizedCommand?.params ?? { stepId: seed.id },
    },
    placement: seed.placement ?? "auto",
    mobileVariant: seed.mobileVariant,
    fallbackExplanation: copy.body,
    isControlStep: Boolean(seed.isControlStep),
    contentVersion: ONBOARDING_CONTENT_VERSION,
  };
});

